// We manage CORS manually via hooks for dynamic origin allowing
fastify.addHook("onRequest", async (request, reply) => {
  incrementInFlight();

  // Maintenance mode gate per PRD §9.2
  if (isMaintenanceMode()) {
    const url = request.url.split("?")[0];
    if (url.startsWith("/v1/") || url.startsWith("/v0/")) {
      return reply
        .header("Retry-After", "30")
        .code(503)
        .send({
          error: {
            message: ERR_MAINTENANCE_ACTIVE_MESSAGE,
            type: "maintenance_active",
            code: ERR_MAINTENANCE_ACTIVE,
          },
        });
    }
    // Block mutating admin requests except database migration / status endpoints
    if (
      request.method !== "GET" &&
      request.method !== "HEAD" &&
      request.method !== "OPTIONS"
    ) {
      if (!url.startsWith("/api/settings/database")) {
        return reply.code(503).send({
          error: "System maintenance in progress",
          code: ERR_MAINTENANCE_ACTIVE,
          message: ERR_MAINTENANCE_ACTIVE_MESSAGE,
        });
      }
    }
  }

  const origin = request.headers.origin;
  if (origin) {
    try {
      const settings = await db
        .select()
        .from(systemSettings)
        .where(eq(systemSettings.key, "corsAllowlist"));
      const allowlistStr =
        settings.length > 0
          ? settings[0].value
          : process.env.NODE_ENV === "production"
            ? "[]"
            : '["*"]';

      const mainDomainSettings = await db
        .select()
        .from(systemSettings)
        .where(eq(systemSettings.key, "mainDomain"));
      const mainDomain =
        mainDomainSettings.length > 0 ? mainDomainSettings[0].value : "";

      const allowlist: string[] = JSON.parse(allowlistStr);

      if (process.env.NODE_ENV === "production") {
        // Production: NEVER allow ["*"] + credentials.
        // If allowlist contains "*", fall back to mainDomain-only matching.
        let isAllowed = false;

        if (allowlist.includes("*")) {
          // Wildcard in prod: only allow same-site (mainDomain and its subdomains)
          if (mainDomain) {
            try {
              const originHost = new URL(origin).hostname;
              isAllowed =
                originHost === mainDomain ||
                originHost.endsWith(`.${mainDomain}`);
            } catch {
              isAllowed = false;
            }
          }
          // If no mainDomain configured, nothing is allowed
        } else {
          // Explicit allowlist: exact match only
          isAllowed = allowlist.includes(origin);
        }

        if (isAllowed) {
          reply.header("Access-Control-Allow-Origin", origin);
          reply.header("Access-Control-Allow-Credentials", "true");
        }
        // If not allowed, no CORS headers = browser blocks the request
      } else {
        // Development: allow wildcard (no credentials reflection needed for dev)
        if (allowlist.includes("*")) {
          reply.header("Access-Control-Allow-Origin", origin);
          reply.header("Access-Control-Allow-Credentials", "true");
        } else if (allowlist.includes(origin)) {
          reply.header("Access-Control-Allow-Origin", origin);
          reply.header("Access-Control-Allow-Credentials", "true");
        }
      }
    } catch (e) {
      // DB not ready yet (bootstrap phase) — allow in dev only
      if (process.env.NODE_ENV !== "production") {
        reply.header("Access-Control-Allow-Origin", origin);
        reply.header("Access-Control-Allow-Credentials", "true");
      }
    }
  }

  // Handle preflight
  if (request.method === "OPTIONS") {
    reply.header(
      "Access-Control-Allow-Methods",
      "GET, POST, PUT, PATCH, DELETE, OPTIONS",
    );
    reply.header(
      "Access-Control-Allow-Headers",
      "Origin, Content-Type, Accept, Authorization, x-api-key, x-anthropic-client, anthropic-version, x-backup-password",
    );
    return reply.send();
  }

  // Setup pending gate
  if (getSetupPending()) {
    const url = request.url.split("?")[0];

    // Always allow setup APIs, health check, setup UI, and static assets
    if (
      url.startsWith("/api/setup") ||
      url === "/api/health" ||
      url.startsWith("/assets/") ||
      url === "/setup" ||
      url === "/favicon.ico"
    ) {
      return;
    }

    // Gateway /v1/* returns clear uninitialized error from packages/shared
    if (url.startsWith("/v1/")) {
      return reply.code(503).send({
        error: {
          message: ERR_SETUP_REQUIRED_MESSAGE,
          type: "uninitialized_error",
          code: ERR_SETUP_REQUIRED,
        },
      });
    }

    // Console and auth routes redirect to /setup with 307
    if (
      url === "/login" ||
      url === "/console" ||
      url === "/admin" ||
      url.startsWith("/api/auth")
    ) {
      return reply.code(307).redirect("/setup");
    }

    // Other API requests return 503
    if (url.startsWith("/api/")) {
      return reply.code(503).send({
        error: "Setup required",
        code: ERR_SETUP_REQUIRED,
        message: ERR_SETUP_REQUIRED_MESSAGE,
      });
    }
  }
});

