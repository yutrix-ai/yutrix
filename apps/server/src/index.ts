// Gracefully handle empty JSON bodies (e.g. for DELETE requests)
const defaultJsonParser = fastify.getDefaultJsonParser("error", "error");
fastify.addContentTypeParser(
  "application/json",
  { parseAs: "string" },
  (request, body, done) => {
    if (body === "" || body == null) {
      return done(null, {});
    }
    return defaultJsonParser(request, body as string, done);
  }
);

